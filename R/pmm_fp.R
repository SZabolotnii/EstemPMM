#' Polynomial Maximization Method with Fractional Polynomial basis
#'
#' Fits a fractional-polynomial regression model with PMM2 (or PMM3, future)
#' estimation of the coefficients. The procedure exhaustively enumerates all
#' non-empty subsets of the FP basis up to size `max_terms` (Royston-Altman
#' 1994), refits each candidate with [lm_pmm2()], and selects the minimiser
#' of the chosen information criterion (BIC or AIC).
#'
#' Two basis tracks are supported (see Zabolotnii 2026, PMM-FP article,
#' frozen decision D1v2):
#'
#' * `track = "pos"` — `P_a = {0, 0.5, 1, 2, 3}` (K = 10 with companions),
#'   requires `E[xi^4] < inf`.
#' * `track = "full"` — `P_b = {-2, -1, -0.5, 0, 0.5, 1, 2, 3}` (K = 16),
#'   additionally requires bounded density at zero and `E[|xi|^-2] < inf`.
#'
#' @param formula a two-sided formula of the form `y ~ x` with exactly one
#'   numeric predictor on the right-hand side. The intercept is added
#'   automatically through the FP design.
#' @param data a data.frame containing `y` and `x`.
#' @param track character: `"pos"` (default) or `"full"`. Selects the basis.
#' @param order integer PMM order; currently only `order = 2` is supported,
#'   `order = 3` is reserved for the symmetric platykurtic case.
#' @param max_terms integer maximum number of FP terms in a candidate model
#'   (default 4; see frozen decision D2).
#' @param criterion character: `"BIC"` (default) or `"AIC"`.
#' @param shift_eps numeric. If `min(x) <= 0`, `x` is shifted by
#'   `-min(x) + shift_eps`. When `NULL`, a default `1e-3` is used.
#' @param kappa_thresh numeric: condition-number threshold for activating
#'   adaptive Tikhonov regularisation on the PMM2 Newton refit
#'   (default `1e8`). Auto-enabled for `track = "full"` candidates.
#' @param max_iter integer: maximum Newton-Raphson iterations per candidate
#'   (default 50).
#' @param tol numeric: convergence tolerance on parameter change (default 1e-6).
#'
#' @return an S4 object of class `PMM_FP_fit` inheriting from `PMM2fit`.
#'   The slot `@nr_diagnostics` is a named numeric vector (see
#'   `.pmm_fp_robust_refit()` for field names), and `@nr_diverged` is
#'   `TRUE` when the OLS fallback was activated.
#'
#' @examples
#' \dontrun{
#'   set.seed(20260511)
#'   n <- 50
#'   x <- runif(n, 0.5, 5)
#'   y <- 1 + 2 * x ^ 0.5 + (rgamma(n, 2) - 2)
#'   fit <- pmm_fp(y ~ x, data = data.frame(x = x, y = y),
#'                 track = "pos", max_terms = 2)
#'   fit@selected_powers
#'   fit@nr_diagnostics
#' }
#'
#' @references
#'   Royston P, Altman DG (1994). Regression using fractional polynomials of
#'   continuous covariates: parsimonious parametric modelling. Appl. Statist.
#'   43(3), 429-467.
#'
#'   Hubin A, Krogdahl T, Lokka A, Kortner T (2026). Bayesian Fractional
#'   Polynomials for Optimal Dosage Estimation. arXiv:2605.06237.
#'
#'   Zabolotnii S (2026). Polynomial Maximization Method with Fractional
#'   Polynomial Basis. In preparation.
#'
#' @export
pmm_fp <- function(formula,
                   data,
                   track        = c("pos", "full"),
                   order        = 2,
                   max_terms    = 4,
                   criterion    = c("BIC", "AIC"),
                   shift_eps    = NULL,
                   kappa_thresh = 1e8,
                   max_iter     = 50L,
                   tol          = 1e-6) {

    call <- match.call()

    # --- argument validation -------------------------------------------------
    track     <- match.arg(track)
    criterion <- match.arg(criterion)

    if (missing(formula) || missing(data)) {
        stop("Both 'formula' and 'data' must be provided")
    }
    if (!inherits(formula, "formula")) {
        stop("'formula' must be a formula object")
    }
    if (!is.data.frame(data)) {
        stop("'data' must be a data.frame")
    }
    if (!order %in% c(2, 3)) {
        stop("'order' must be 2 or 3 (only 2 is implemented in this version)")
    }
    if (order == 3) {
        stop("PMM3 dispatch in pmm_fp() is not implemented yet")
    }
    if (!is.numeric(max_terms) || max_terms < 1) {
        stop("'max_terms' must be a positive integer")
    }

    # --- extract response and single predictor -------------------------------
    mf <- stats::model.frame(formula, data)
    y  <- stats::model.response(mf)
    rhs_vars <- attr(stats::terms(formula), "term.labels")
    if (length(rhs_vars) != 1L) {
        stop("pmm_fp() currently supports a single numeric predictor on RHS")
    }
    x_name <- rhs_vars[1]
    x <- mf[[x_name]]
    if (!is.numeric(x)) {
        stop("predictor '", x_name, "' must be numeric")
    }

    # --- preprocessing: shift to ensure x > 0 --------------------------------
    if (is.null(shift_eps)) shift_eps <- 1e-3
    applied_shift <- 0
    if (min(x) <= 0) {
        applied_shift <- -min(x) + shift_eps
        x <- x + applied_shift
    }
    n <- length(y)

    # --- basis selection (D1v2) ----------------------------------------------
    powers <- switch(track,
                     pos  = c(0, 0.5, 1, 2, 3),
                     full = c(-2, -1, -0.5, 0, 0.5, 1, 2, 3))

    # For full track: auto-enable Tikhonov (negative powers may cause ill-conditioning)
    force_tikhonov <- (track == "full")

    # --- enumerate candidates ------------------------------------------------
    candidates <- .enumerate_fp_models(powers, max_terms)

    # --- fit candidates ------------------------------------------------------
    ic_records <- data.frame(
        index   = seq_along(candidates),
        powers  = vapply(candidates,
                         function(p) paste(p, collapse = ","),
                         character(1)),
        n_terms = vapply(candidates, length, integer(1)),
        BIC     = NA_real_,
        AIC     = NA_real_,
        stringsAsFactors = FALSE
    )

    best_fit      <- NULL
    best_powers   <- NULL
    best_ic       <- Inf
    best_diag     <- NULL
    best_diverged <- FALSE

    for (i in seq_along(candidates)) {
        p_vec <- candidates[[i]]

        # Build FP design matrix (with intercept)
        fp_cols <- vapply(p_vec, function(p) .fp_transform(x, p), numeric(n))
        if (!is.matrix(fp_cols)) fp_cols <- matrix(fp_cols, ncol = length(p_vec))
        # Prepend intercept column
        X_cand <- cbind(1, fp_cols)
        colnames(X_cand) <- c("(Intercept)", paste0("fp", seq_along(p_vec)))

        # Get OLS moments (same computation as lm_pmm2 uses internally)
        b_ols_cand <- tryCatch(
            as.numeric(lm.fit(X_cand, y)$coefficients),
            error = function(e) NULL
        )
        if (is.null(b_ols_cand) || any(!is.finite(b_ols_cand))) {
            ic_records$BIC[i] <- Inf
            ic_records$AIC[i] <- Inf
            next
        }
        res_ols <- y - as.vector(X_cand %*% b_ols_cand)
        m2_c <- mean(res_ols^2)
        m3_c <- mean(res_ols^3)
        m4_c <- mean(res_ols^4)

        if (m2_c <= 0 || !is.finite(m2_c)) {
            ic_records$BIC[i] <- Inf
            ic_records$AIC[i] <- Inf
            next
        }

        # Robust refit with all four safeguards (quiet_fallback=TRUE during sweep)
        rr <- tryCatch(
            .pmm_fp_robust_refit(
                X                     = X_cand,
                y                     = y,
                m2                    = m2_c,
                m3                    = m3_c,
                m4                    = m4_c,
                max_iter              = max_iter,
                tol                   = tol,
                kappa_thresh          = kappa_thresh,
                use_adaptive_tikhonov = if (force_tikhonov) TRUE else NULL,
                quiet_fallback        = TRUE
            ),
            error = function(e) NULL
        )

        if (is.null(rr)) {
            ic_records$BIC[i] <- Inf
            ic_records$AIC[i] <- Inf
            next
        }

        # Fake a minimal PMM2fit for .fp_ic()
        rss <- sum(rr$residuals^2)
        k_p <- ncol(X_cand)
        if (rss <= 0 || !is.finite(rss)) {
            ic_records$BIC[i] <- Inf
            ic_records$AIC[i] <- Inf
            next
        }
        ll      <- -n / 2 * (log(2 * pi) + log(rss / n) + 1)
        bic_val <- -2 * ll + log(n) * k_p
        aic_val <- -2 * ll + 2   * k_p
        ic_records$BIC[i] <- bic_val
        ic_records$AIC[i] <- aic_val
        ic_val <- if (criterion == "BIC") bic_val else aic_val

        if (ic_val < best_ic) {
            # Store enough info to reconstruct a PMM2fit-compatible result
            best_ic       <- ic_val
            best_powers   <- p_vec
            best_rr       <- rr
            best_m2       <- m2_c
            best_m3       <- m3_c
            best_m4       <- m4_c
            best_diag     <- rr$diagnostics
            best_diverged <- rr$nr_diverged
        }
    }

    if (is.null(best_powers)) {
        stop("pmm_fp(): no candidate model could be fitted")
    }

    # Report fallback for the selected model (once, post-sweep)
    if (isTRUE(best_diverged)) {
        message("[pmm_fp] Selected model used OLS-FP fallback (nr_diverged=TRUE). ",
                "Consider increasing max_iter or checking the design.")
    }

    # --- assemble PMM_FP_fit object ------------------------------------------
    new("PMM_FP_fit",
        coefficients    = best_rr$b,
        residuals       = best_rr$residuals,
        m2              = best_m2,
        m3              = best_m3,
        m4              = best_m4,
        convergence     = best_rr$convergence,
        iterations      = best_rr$iterations,
        call            = call,
        selected_powers = best_powers,
        track           = track,
        all_models_ic   = ic_records,
        criterion       = criterion,
        shift_eps       = applied_shift,
        nr_diagnostics  = best_diag,
        nr_diverged     = best_diverged)
}
